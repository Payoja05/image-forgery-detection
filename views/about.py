with t2:
    section("Limitations")
    st.markdown(
        "- Trained on synthetic forgeries; accuracy on real-world edits (CASIA etc.) is **not measured** here.\n"
        "- Not designed for AI-generated images, inpainting by diffusion models, or whole-image filters.\n"
        "- Large images are down-scaled to 512 px, which can erase traces of very small edits.\n"
        "- Copy-move detection reports only the largest consistent cluster.\n"
        "- Scores are not calibrated probabilities of forgery."
    )
